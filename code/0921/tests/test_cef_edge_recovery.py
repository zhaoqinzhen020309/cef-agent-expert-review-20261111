from types import SimpleNamespace
import pytest
from cef.store import Archive
from cef.tool_session import ToolSession,ToolSessionError
from resumeCEFTools import authorize_edge_retry,is_cloudfront_rejection

ERROR='PermissionDeniedError: <HTML><H1>403 ERROR</H1>Request blocked. Generated by cloudfront (CloudFront)</HTML>'

def session(tmp_path,message=None,error=ERROR):
    provider=Archive(tmp_path/'provider')
    s=ToolSession(tmp_path/'task',SimpleNamespace(config={},archive=provider),[],None,
                  role='data_designer',system='test',payload={},runtime_v2=True)
    s.archive.add('model_started',dict(turn=1,provider_start_seq=0))
    req=provider.add('provider_request',dict(role=s.role,messages=s.messages,request_parameters=dict(tools=[])))
    provider.add('provider_response',dict(request_seq=req['seq'],message=message,error_chain=[error]))
    return s

def test_only_identified_cloudfront_rejection_is_recoverable():
    assert is_cloudfront_rejection([ERROR])
    assert not is_cloudfront_rejection(['PermissionDeniedError: {"error":"invalid key"}'])
    assert not is_cloudfront_rejection(['PermissionDeniedError: 403 Cloudflare'])

def test_explicit_edge_retry_keeps_failed_records_and_authorizes_once(tmp_path):
    s=session(tmp_path);before=list(s.model.archive.records)
    receipt=authorize_edge_retry(s)
    assert receipt['turn']==1 and receipt['recovery_kind']=='explicit_cloudfront_403'
    assert s.model.archive.records==before
    with pytest.raises(ToolSessionError,match='unused'):authorize_edge_retry(s)

def test_edge_retry_cannot_discard_usable_message(tmp_path):
    with pytest.raises(ToolSessionError,match='usable'):authorize_edge_retry(session(tmp_path,dict(role='assistant',content='done')))

def test_authorized_edge_retry_dispatches_saved_messages_once(tmp_path):
    s=session(tmp_path);receipt=authorize_edge_retry(s);calls=[]
    def exchange(messages,tools,role):
        calls.append((messages,tools,role))
        return dict(message=dict(role='assistant',content='verified response'),finish_reason='stop')
    s.model.exchange=exchange
    result=s._recover_model(s.archive.of('model_started')[0])
    assert result['message']['content']=='verified response'
    assert calls==[(receipt['messages'],[],s.role)]
    assert s.archive.of('retry_started')[0]['authorization_seq']==1+next(
        r['seq'] for r in s.archive.records if r['kind']=='model_started')


BALANCE_ERROR="APIStatusError: Error code: 402 - {'error': {'message': 'Insufficient Balance', 'type': 'insufficient_balance_error'}}"


def test_recharged_402_requires_available_balance_and_exact_rejection(tmp_path):
    from resumeCEFTools import authorize_balance_retry
    s=session(tmp_path,error=BALANCE_ERROR)
    with pytest.raises(ToolSessionError,match='balance'):
        authorize_balance_retry(s,dict(is_available=False,balance_infos=[]))
    assert not s.archive.of('retry_authorized')
    receipt=authorize_balance_retry(s,dict(is_available=True,balance_infos=[dict(total_balance='9.98')]))
    assert receipt['recovery_kind']=='explicit_recharged_402'
    assert s.archive.of('balance_recovery_check')
    with pytest.raises(ToolSessionError,match='unused'):
        authorize_balance_retry(s,dict(is_available=True,balance_infos=[dict(total_balance='9.98')]))


def test_positive_balance_does_not_authorize_other_provider_errors(tmp_path):
    from resumeCEFTools import authorize_balance_retry
    s=session(tmp_path,error='APIStatusError: Error code: 401 - invalid key')
    with pytest.raises(ToolSessionError,match='recorded error'):
        authorize_balance_retry(s,dict(is_available=True,balance_infos=[dict(total_balance='9.98')]))
