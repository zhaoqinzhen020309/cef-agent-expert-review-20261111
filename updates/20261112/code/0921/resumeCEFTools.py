"""Explicitly retry one recorded native-tool network failure, then resume."""
import argparse
import copy
from decimal import Decimal
from pathlib import Path
from types import SimpleNamespace

from cef.cli import claim_owner
from cef.config import file_hash,load_json,validate
from cef.store import Archive
from cef.tool_session import ToolSession,ToolSessionError


def is_cloudfront_rejection(errors):
    return any(isinstance(error,str) and error.startswith('PermissionDeniedError:')
               and all(token in error.lower() for token in ('403','request blocked','generated by cloudfront'))
               for error in errors or [])


def authorize_edge_retry(session):
    """Explicit manual redispatch only; never automatically retry permission errors."""
    return _authorize_rejection(session,is_cloudfront_rejection,'explicit_cloudfront_403')


def is_balance_rejection(errors):
    return any(isinstance(error,str) and error.startswith('APIStatusError: Error code: 402 -')
               and 'Insufficient Balance' in error and 'insufficient_balance_error' in error
               for error in errors or [])


def authorize_balance_retry(session,balance):
    if (balance.get('is_available') is not True or not any(
            Decimal(row['total_balance'])>0 for row in balance.get('balance_infos',[]))):
        raise ToolSessionError('provider balance is not available; no retry authorized')
    receipt=_authorize_rejection(session,is_balance_rejection,'explicit_recharged_402')
    session.archive.add('balance_recovery_check',dict(authorization_seq=session.archive.records[-1]['seq'],balance=balance))
    return receipt


def _authorize_rejection(session,predicate,kind):
    completed={r['turn'] for r in session.archive.of('model_completed')}
    pending=[r for r in session.archive.of('model_started') if r['turn'] not in completed]
    if len(pending)!=1 or session.archive.of('submitted'):
        raise ToolSessionError('edge retry requires exactly one pending exchange')
    session.messages=copy.deepcopy(session.archive.of('messages')[-1])
    request,response=session._pending_attempt(pending[0])
    result=response['data']
    if result.get('message'):raise ToolSessionError('usable provider message cannot be retried')
    if not predicate(result.get('error_chain')):
        raise ToolSessionError('explicit rejection retry does not match the recorded error')
    used={r['authorization_seq'] for r in session.archive.of('retry_started')}
    if any(r['kind']=='retry_authorized' and r['seq'] not in used and
           r['data']['failed_request_seq']==request['seq'] for r in session.archive.records):
        raise ToolSessionError('this failed exchange already has an unused retry authorization')
    receipt=dict(turn=pending[0]['turn'],failed_request_seq=request['seq'],failed_response_seq=response['seq'],
                 messages=copy.deepcopy(session.messages),recovery_kind=kind,
                 helper_sha256=file_hash(Path(__file__)),
                 policy='One user-requested redispatch of the saved exchange; failed evidence and unknown usage retained; no tool or evaluation replay.')
    session.archive.add('retry_authorized',receipt)
    return receipt


def _authorize_owned(folder,relative_task,check=False):
    folder=Path(folder).resolve()
    config=validate(load_json(folder/'search_config.json'))
    if not config.get('agent_tool_loop_v1') or Path(config['run_dir']).resolve()!=folder/'search':
        raise ValueError('native tool-loop run folder required')
    for source in config['implementation_source_manifest']:
        if file_hash(source['path'])!=source['sha256']:
            raise ValueError('frozen source changed: '+source['path'])
    relative=Path(relative_task)
    if relative.is_absolute():raise ValueError('task must be relative to the run folder')
    task=(folder/relative).resolve()
    task.relative_to(folder)
    if not (task/'session/facts.jsonl').is_file():raise ValueError('saved task session required')
    archive=Archive(task/'session')
    identity=archive.of('identity')[0]
    role=identity['role']
    if role=='data_designer':
        if task.parent.name!='data' or task.name!='agent_task' or task.parents[2].name!='rounds':
            raise ValueError('invalid Data task path')
        provider=Archive(folder/'data_agent')
    elif role in ('planner','editor'):
        if task.parent!=folder/'search/agent_tasks':raise ValueError('invalid algorithm task path')
        provider=Archive(folder/'search')
    else:raise ValueError('unsupported role')
    # Rebuild only the journal interface; authorization never accesses the API.
    model=SimpleNamespace(config=identity['model'],archive=provider)
    session=ToolSession(task,model,identity['tools'],None,role=role,
        system=identity['system'],payload=identity['payload'],max_turns=identity['max_turns'],
        finalize_turns=identity.get('finalize_turns',0),runtime_v2=identity.get('runtime_version')==2,
        context_window_tokens=identity.get('context_window_tokens'),completion_tools=identity.get('completion_tools'),
        checkpoint_tools=identity.get('checkpoint_tools'))
    if check:
        print('Saved native task | role='+role+' | no request or retry authorization',flush=True)
        return config
    pending=[r for r in session.archive.of('model_started') if r['turn'] not in {x['turn'] for x in session.archive.of('model_completed')}]
    edge=False;balance_error=False
    if len(pending)==1:
        session.messages=copy.deepcopy(session.archive.of('messages')[-1])
        _,response=session._pending_attempt(pending[0])
        edge=is_cloudfront_rejection(response['data'].get('error_chain'))
        balance_error=is_balance_rejection(response['data'].get('error_chain'))
    if balance_error:
        from cef.cli import load_env
        from cef.billing import balance_snapshot
        load_env(Path(__file__).with_name('.env'))
        receipt=authorize_balance_retry(session,balance_snapshot(config))
    else:receipt=authorize_edge_retry(session) if edge else session.authorize_failed_exchange_retry()
    print('Explicit request retry authorized | role='+role+' | turn='+str(receipt['turn']),flush=True)
    return config


def authorize(folder,relative_task,check=False):
    folder=Path(folder).resolve()
    config=validate(load_json(folder/'search_config.json'))
    if Path(config['run_dir']).resolve()!=folder/'search':
        raise ValueError('run directory mismatch')
    # Archive construction can repair a torn append. Own the run before opening
    # any journal, including when only checking the selected task.
    lease=claim_owner(config['run_dir'])
    try:return _authorize_owned(folder,relative_task,check)
    finally:lease.unlink()


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--resume',type=Path,required=True)
    parser.add_argument('--task',required=True,help='relative saved task path, for example search/agent_tasks/step_0_planner')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args(argv)
    config=authorize(args.resume,args.task,args.check)
    if not args.check:
        # Use the normal entry to retain single-console and persistent logging.
        from cef_log_output import launch
        from runCEFAuto import CONFIG
        return launch(CONFIG,['--resume',str(args.resume.resolve())])
    return 0


if __name__=='__main__':raise SystemExit(main())
